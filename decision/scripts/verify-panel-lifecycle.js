async (page) => {
  const checks=[],errors=[];
  const onError=e=>errors.push(e.message);page.on('pageerror',onError);
  const expect=async(name,fn)=>{if(!await fn())throw new Error(name);checks.push(name);};
  await page.bringToFront();await page.setViewportSize({width:1440,height:960});
  await page.keyboard.press('Escape');await page.locator('#screen-site').selectOption('campus');
  await page.locator('#sb-run').waitFor({state:'attached',timeout:60000});await page.waitForFunction(()=>!document.querySelector('#refresh-all').disabled);
  await page.locator('#dock-tab-sandbox').click();
  await page.locator('#sb-auto').uncheck();
  await page.locator('.screen-nav [data-screen-panel="risk"]').click();
  if (!await page.locator('#region-duration').isVisible()) await page.locator('.regional-parameters > summary').click();
  await page.locator('#region-ai').uncheck();
  await page.locator('#region-grid-resolution').selectOption('100');
  await page.locator('#region-duration').fill('37');
  await page.evaluate(()=>{window.qaPanelForm=document.querySelector('#regional-form');document.querySelector('.screen-nav [data-screen-panel="risk"]').click();});
  await expect('active panel is not remounted',()=>page.evaluate(()=>window.qaPanelForm===document.querySelector('#regional-form')));
  await page.evaluate(()=>{document.querySelector('#screen-panel-close').click();document.querySelector('.screen-nav [data-screen-panel="risk"]').click();});
  await page.waitForTimeout(100);
  await expect('close-reopen keeps new panel and draft',async()=>await page.locator('#region-duration').inputValue()==='37'&&await page.locator('#screen-drawer').isVisible());
  if (!await page.locator('#regional-submit').isVisible()) await page.locator('.regional-parameters > summary').click();
  const pending=page.waitForResponse(r=>r.url().endsWith('/api/weather/aic/regional-assess')&&r.request().method()==='POST',{timeout:70000});
  await page.locator('#regional-submit').click();
  const response=await pending;if(!response.ok())throw new Error('Real regional assessment failed: '+response.status());
  const report=await response.json();
  await page.locator('.regional-audit').waitFor({state:'attached'});
  await expect('report table renders at most eighty rows',async()=>await page.locator('#regional-result tbody tr').count()===Math.min(80,report.samples.length));
  await expect('page displays exact API report hash',async()=>(await page.locator('.regional-audit').textContent()).includes(report.report_sha256));
  await page.evaluate(()=>{window.qaPanelForm=document.querySelector('#regional-form');document.querySelector('#refresh-all').dispatchEvent(new Event('click'));});
  await page.waitForFunction(()=>!document.querySelector('#refresh-all').disabled);
  await expect('weather refresh preserves risk form and current report',async()=>await page.evaluate(()=>window.qaPanelForm===document.querySelector('#regional-form'))&&(await page.locator('.regional-audit').textContent()).includes(report.report_sha256));
  await page.locator('#screen-panel-close').click();await page.locator('#screen-drawer').waitFor({state:'hidden'});
  await page.evaluate(()=>{window.qaOriginalURL=URL.createObjectURL;URL.createObjectURL=function(blob){window.qaReportExport=blob.text();return window.qaOriginalURL.call(this,blob);};});
  const downloaded=page.waitForEvent('download');await page.locator('#screen-export').click();const download=await downloaded;
  const output=await page.evaluate(async()=>JSON.parse(await window.qaReportExport));
  await expect('screen export links to same regional API result',()=>(output.record||output).regional_report?.report_sha256===report.report_sha256);
  await expect('export retains complete sample evidence',()=>(output.record||output).regional_report.samples.length===report.samples.length);
  await download.delete();
  await page.evaluate(()=>{URL.createObjectURL=window.qaOriginalURL;delete window.qaOriginalURL;delete window.qaReportExport;delete window.qaPanelForm;document.querySelector('[data-screen-panel="evidence"]').click();});
  await page.locator('#source-search').fill('WHO');
  await page.evaluate(()=>document.querySelector('#refresh-all').dispatchEvent(new Event('click')));
  await page.waitForFunction(()=>!document.querySelector('#refresh-all').disabled);
  await expect('evidence refresh preserves source filter',async()=>await page.locator('#source-search').inputValue()==='WHO');
  await page.locator('#screen-panel-close').click();await page.locator('#screen-drawer').waitFor({state:'hidden'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('#dock-tab-risk').click();
  await page.locator('.screen-person-row').first().click();
  await expect('mobile reopened report retains exact hash',async()=>(await page.locator('.regional-audit').textContent()).includes(report.report_sha256));
  await expect('mobile risk drawer has no horizontal overflow',()=>page.locator('#screen-drawer').evaluate(node=>node.scrollWidth<=node.clientWidth));
  await page.screenshot({path:'output/playwright/conflicts-panel-mobile.png'});
  await page.locator('#screen-panel-close').click();await page.locator('#screen-drawer').waitFor({state:'hidden'});
  await page.setViewportSize({width:1440,height:960});
  await page.locator('.screen-nav [data-screen-panel="risk"]').click();
  let redundantHeatRequests=0;
  const countHeat=req=>{if(req.url().endsWith('/sandbox/heatmap'))redundantHeatRequests++;};
  page.on('request',countHeat);
  try{
    if (!await page.locator('#region-duration').isVisible()) await page.locator('.regional-parameters > summary').click();
    await page.locator('#region-duration').fill('41');
    await page.locator('[name="regional-group"][value="athletes"]').uncheck();
    await page.waitForTimeout(200);
    await expect('cohort changes invalidate obsolete report',async()=>await page.locator('.regional-audit').count()===0);
    await expect('cohort changes reuse the same weather grid',()=>redundantHeatRequests===0);
  }finally{page.off('request',countHeat);}
  await page.locator('#screen-panel-close').click();await page.locator('#screen-drawer').waitFor({state:'hidden'});
  await expect('no uncaught page errors',()=>errors.length===0);page.off('pageerror',onError);
  return {url:page.url(),checks,errors,report_sha256:report.report_sha256,note:'Real rule-baseline regional request; no simulated weather or generated medical advice.'};
}
