async (page) => {
  const checks=[];
  const expect=async(name,fn)=>{if(!await fn())throw new Error(name);checks.push(name);};
  await page.setViewportSize({width:1440,height:960});
  await page.keyboard.press('Escape');
  await page.locator('#map-orbit').click();
  const base=page.url().split('#')[0];
  await page.goto(base+'#spatial');
  await page.locator('[data-operation="add"]').waitFor();
  await expect('workbench does not inherit rotating screen state',async()=>await page.locator('#workspace-map').getAttribute('data-interaction')==='inspect'&&await page.locator('#map-orbit').getAttribute('aria-pressed')==='false');
  await expect('workbench has only one map',async()=>await page.locator('.maplibregl-canvas').count()===1);
  await page.locator('[data-operation="add"]').click();
  await page.locator('#layer-buildings').uncheck();
  await expect('hiding buildings exits editing',async()=>await page.locator('#workspace-map').getAttribute('data-interaction')==='inspect');
  await page.locator('[data-operation="add"]').click();
  await expect('editing restores visible building context',()=>page.locator('#layer-buildings').isChecked());
  await page.locator('#map-orbit').click();
  await page.locator('#map-orbit').click();
  await expect('workbench rotation toggles correctly',async()=>await page.locator('#workspace-map').getAttribute('data-interaction')==='inspect'&&await page.locator('#map-orbit').getAttribute('aria-pressed')==='false');
  await page.goto(base+'#screen');
  await page.locator('[data-operation="add"]').waitFor();
  await expect('returning to screen starts idle',async()=>await page.locator('#workspace-map').getAttribute('data-interaction')==='inspect');
  await expect('screen has only one map after navigation',async()=>await page.locator('.maplibregl-canvas').count()===1);
  await page.locator('[data-operation="add"]').click();
  await page.screenshot({path:'output/playwright/interaction-active-desktop.png'});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:320,height:844});
  await page.locator('.sandbox-mobile-toggle').click();
  await page.locator('[data-operation="add"]').click();
  await page.locator('#workspace-map').scrollIntoViewIfNeeded();
  const notice=await page.locator('.map-interaction').boundingBox(),cancel=await page.locator('[data-interaction-cancel]').boundingBox();
  await expect('mobile mode notice and cancel stay in viewport',()=>Promise.resolve(notice.x>=0&&notice.x+notice.width<=320&&cancel.width>=32&&cancel.height>=40));
  await page.locator('[data-interaction-editor]').click();
  await expect('mobile mode notice opens editor',async()=>await page.locator('.sandbox-mobile-toggle').getAttribute('aria-expanded')==='true');
  await page.locator('.sandbox-mobile-close').click();
  await page.screenshot({path:'output/playwright/interaction-active-mobile.png'});
  await page.locator('[data-interaction-cancel]').click();
  return {url:page.url(),checks};
}
