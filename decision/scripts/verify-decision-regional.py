"""Check substantive group reasoning without the sandbox layout context."""
import json
from pathlib import Path

import httpx

from backend.aic.store import digest

payload = {
    "area_kind": "campus", "mode": "history", "data_mode": "lcz_simulation",
    "grid_resolution_m": 50, "groups": ["students", "workers", "older_adults", "children"],
    "activity": "walk", "exposure_minutes": 30, "use_ai": True,
    "bounds": {"west": 113.528, "east": 113.532, "south": 34.816, "north": 34.820},
    "cohort_scenarios": {
        "students": {"activity": "run", "exposure_minutes": 60},
        "workers": {"activity": "work", "exposure_minutes": 120},
        "older_adults": {"activity": "rest", "exposure_minutes": 20},
    },
}
with httpx.Client(base_url="https://weather.nogamenolife.cn", timeout=115) as client:
    report = client.post("/api/weather/aic/regional-assess", json=payload).raise_for_status().json()
Path("output/playwright/decision-regional-public.json").write_text(
    json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
checks = []


def check(value, name):
    assert value, name
    checks.append(name)


a = report["decision_analysis"]
check(a["mode"] == "ai_grounded_decision", "standalone regional analysis is generated by DeepSeek")
check(a["building"] is None, "no building decision is invented without a layout context")
check({c["group"] for c in a["cohorts"]} == set(payload["groups"]), "each selected group has a judgement")
contexts = {c["id"]: c["context"] for c in report["cohorts"]}
check(contexts["workers"]["activity"] == "work" and contexts["workers"]["minutes"] == 120,
      "actual group activity and duration are preserved")
check(all(c["reasoning"]["fact_ids"] for c in a["cohorts"]), "every group reason cites computed evidence")
check(all(not c["medical_advice_ids"] for c in a["cohorts"]), "simulation cannot release medical treatment")
check(all("BG-EXERTION" not in c["reasoning"]["knowledge_ids"] for c in a["cohorts"]
          if c["group"] in {"children", "older_adults"}), "professional background remains group applicable")
check(report["report_sha256"] == digest({k: v for k, v in report.items() if k != "report_sha256"}),
      "standalone report digest includes generated reasoning")
print(json.dumps({"checks": checks, "mode": a["mode"], "report_sha256": report["report_sha256"]}, ensure_ascii=False, indent=2))
